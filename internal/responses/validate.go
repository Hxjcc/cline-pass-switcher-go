package responses

import (
	"fmt"

	"github.com/munmunjaklin458-afk/cline-pass-switcher-go/internal/jsonx"
)

// RequestError identifies unsupported semantics before any upstream request is
// made. Param points to the offending protocol field, not to user tool data.
type RequestError struct {
	Code    string
	Param   string
	Message string
}

func (err *RequestError) Error() string { return err.Message }

func unsupported(param, capability string) error {
	return &RequestError{Param: param, Message: capability + " is not supported by this Chat-backed proxy"}
}

func validateRequestCapabilities(body map[string]any) error {
	if body["conversation"] != nil {
		return unsupported("conversation", "server-side conversation state; send the full conversation in input")
	}
	if body["background"] == true {
		return unsupported("background", "background response execution")
	}
	if err := validateToolDefinitions(body["tools"], "tools", 0); err != nil {
		return err
	}
	if choice := jsonx.Map(body["tool_choice"]); choice != nil {
		switch kind := jsonx.String(choice["type"]); kind {
		case "function", "custom", "tool_search":
		default:
			return unsupported("tool_choice.type", "tool choice type "+kind)
		}
	}
	for index, raw := range jsonx.Slice(body["input"]) {
		item := jsonx.Map(raw)
		if item == nil {
			continue
		}
		path := fmt.Sprintf("input[%d]", index)
		switch kind := jsonx.String(item["type"]); kind {
		case "", "message":
			if err := validateMessageContent(item["content"], path+".content"); err != nil {
				return err
			}
		case "input_text", "input_image", "input_file", "input_audio":
			if err := validateMessageContent([]any{item}, path); err != nil {
				return err
			}
		case "function_call", "custom_tool_call", "tool_search_call":
		case "function_call_output", "custom_tool_call_output":
			if err := validateToolOutputMedia(item["output"], path+".output", 0); err != nil {
				return err
			}
		case "additional_tools", "tool_search_output":
			if err := validateToolDefinitions(item["tools"], path+".tools", 0); err != nil {
				return err
			}
		case "compaction_trigger":
			// Remote compaction v2 marker: Codex asks the provider to compact
			// the conversation inside this request. It carries no payload.
		case "compaction":
			if _, ok := compactionSummaryFromEnvelope(jsonx.String(item["encrypted_content"])); !ok {
				return unsupported(path+".encrypted_content", "compaction generated by another provider or an unreadable compaction envelope")
			}
		case "reasoning":
			if jsonx.String(item["encrypted_content"]) != "" && reasoningTextFromItem(item) == "" {
				return unsupported(path+".encrypted_content", "encrypted-only reasoning from another provider")
			}
		case "agent_message":
			// Remote multi-agent v2 envelope (task assignment, teammate
			// reply, error report). Its content mixes readable text with
			// payload blobs; the bridge folds it into a single user turn.
		default:
			return unsupported(path+".type", "input item type "+kind)
		}
	}
	return nil
}

func validateToolDefinitions(value any, path string, depth int) error {
	if depth > 16 {
		return unsupported(path, "tool namespace nesting deeper than 16 levels")
	}
	for index, raw := range jsonx.Slice(value) {
		tool := jsonx.Map(raw)
		if tool == nil {
			continue
		} // Codex's string custom-tool shorthand.
		if isUnforwardedTool(tool) {
			continue
		}
		field := fmt.Sprintf("%s[%d]", path, index)
		switch kind := jsonx.String(tool["type"]); kind {
		case "", "function", "custom":
		case "namespace":
			if err := validateToolDefinitions(tool["tools"], field+".tools", depth+1); err != nil {
				return err
			}
		case "tool_search":
		default:
			return unsupported(field+".type", "tool type "+kind)
		}
	}
	return nil
}

func validateMessageContent(value any, path string) error {
	for index, raw := range jsonx.Slice(value) {
		part := jsonx.Map(raw)
		field := fmt.Sprintf("%s[%d]", path, index)
		switch kind := jsonx.String(part["type"]); kind {
		case "input_text", "output_text", "text", "refusal":
		case "input_image", "image_url", "image", "output_image":
			if _, ok := imageURLPart(part); !ok {
				return unsupported(field, "image without a URL or inline data; file_id image references")
			}
		default:
			return unsupported(field+".type", "content type "+kind)
		}
	}
	return nil
}

// A tool result string is opaque business data. Only inspect explicit content
// blocks/wrappers, never arbitrary JSON keys inside tool results.
func validateToolOutputMedia(value any, path string, depth int) error {
	if depth > 20 {
		return nil
	}
	switch typed := value.(type) {
	case []any:
		for index, raw := range typed {
			if err := validateToolOutputMedia(raw, fmt.Sprintf("%s[%d]", path, index), depth+1); err != nil {
				return err
			}
		}
	case map[string]any:
		switch kind := jsonx.String(typed["type"]); kind {
		case "input_file", "input_audio", "audio", "output_audio":
			return unsupported(path+".type", "tool output content type "+kind)
		case "input_image", "image_url", "image", "output_image":
			if _, ok := imageURLPart(typed); !ok {
				return unsupported(path, "image without a URL or inline data; file_id image references")
			}
		}
		for _, key := range []string{"content", "output"} {
			if _, ok := typed[key].([]any); ok {
				if err := validateToolOutputMedia(typed[key], path+"."+key, depth+1); err != nil {
					return err
				}
			}
		}
	}
	return nil
}
